export function buildCatalog(
  overrides: Record<string, IngredientOverride> = {},
): IngredientCatalog {
  return Object.fromEntries(
    ingredients.map((item) => [
      item.id,
      {
        ...item,
        ...overrides[item.id],
        nutritionPer100g: {
          ...item.nutritionPer100g,
          ...overrides[item.id]?.nutritionPer100g,
        },
      },
    ]),
  );
}
